"""
Generate a random CNC job dataset similar to the example:
    jobs = [
        Job(job_id=1, machine_id="M1", setup_time=10.0, proc_time=45.0),
        ...
    ]

Specifications:
- Processing time distribution: Normal(mean=45, sigma=25)
- Number of jobs: random in [5, 15] (or specify)
- Number of machines: random in [3, 10] (or specify)
- Setup time: fixed (default 10.0)
- Operators: fixed = 1 (not modelled in generator)
- Reproducible via seed
- Outputs:
    - prints Python-style 'jobs = [...]' list
    - saves CSV with columns: job_id,machine_id,setup_time,proc_time,release_time
"""

import csv
import argparse
import os
import random
from dataclasses import dataclass, asdict
from typing import List

@dataclass
class Job:
    job_id: int
    machine_id: str
    setup_time: float
    proc_time: float
    release_time: float = 0.0

def generate_cnc_dataset(n_jobs_min:int,
                         n_jobs_max:int,
                         n_machines_min:int,
                         n_machines_max:int,
                         fixed_setup:float,
                         proc_mean:float,
                         proc_sigma:float,
                         seed:int = None,
                         n_jobs_spec:int = None,
                         n_machines_spec:int = None
                         ) -> List[Job]:
    """
    Generate a list of Job objects according to the requested ranges and distributions.
    - If n_jobs_spec is provided, it overrides the random pick from [n_jobs_min, n_jobs_max].
    - If n_machines_spec is provided, it overrides the random pick from [n_machines_min, n_machines_max].
    - Processing times: normal(proc_mean, proc_sigma), then clipped to >= 1.0 (minutes).
    - Machine assignment: uniform random among M1..M_{n_machines}.
    """
    if seed is not None:
        random.seed(seed)

    # decide counts
    if n_jobs_spec is None:
        n_jobs = random.randint(n_jobs_min, n_jobs_max)
    else:
        n_jobs = int(n_jobs_spec)
    if n_machines_spec is None:
        n_machines = random.randint(n_machines_min, n_machines_max)
    else:
        n_machines = int(n_machines_spec)

    jobs = []
    for j in range(1, n_jobs + 1):
        # choose machine
        machine_id = f"M{random.randint(1, n_machines)}"
        # draw processing time from Normal(mean, sigma)
        pt = random.gauss(proc_mean, proc_sigma)
        # clip to avoid non-positive times
        pt = max(1.0, pt)
        # setup time fixed
        st = float(fixed_setup)
        jobs.append(Job(job_id=j, machine_id=machine_id, setup_time=st, proc_time=round(pt, 2), release_time=0.0))

    return jobs

def print_jobs_python_list(jobs: List[Job]) -> None:
    """
    Print the jobs in the Python list literal format like the example the user gave.
    """
    print("jobs = [")
    for job in jobs:
        print(f"    Job(job_id={job.job_id}, machine_id=\"{job.machine_id}\", setup_time={job.setup_time}, proc_time={job.proc_time}),")
    print("]")

def save_jobs_csv(jobs: List[Job], filepath: str) -> None:
    os.makedirs(os.path.dirname(filepath) or ".", exist_ok=True)
    with open(filepath, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["job_id","machine_id","setup_time","proc_time","release_time"])
        writer.writeheader()
        for job in jobs:
            writer.writerow(asdict(job))

def summary_statistics(jobs: List[Job]) -> None:
    proc_times = [j.proc_time for j in jobs]
    n = len(proc_times)
    mean = sum(proc_times) / n if n>0 else 0.0
    var = sum((x-mean)**2 for x in proc_times) / n if n>0 else 0.0
    std = var**0.5
    print(f"\nSummary (n_jobs={n}):")
    print(f"  Generated processing times: mean={mean:.2f}, std={std:.2f}, min={min(proc_times):.2f}, max={max(proc_times):.2f}")

def main():
    jobs = generate_cnc_dataset(
        n_jobs_min=5, n_jobs_max=15,
        n_machines_min=3, n_machines_max=10,
        fixed_setup=10,
        proc_mean=45,
        proc_sigma=25,
        seed=None,
        n_jobs_spec=None,
        n_machines_spec=None
    )

    # print Python-style list (example format requested)
    print_jobs_python_list(jobs)

    # save CSV
    save_jobs_csv(jobs, "dataset.out")
    print(f"\nSaved CSV to: dataset.out")

    # summary statistics
    summary_statistics(jobs)

if __name__ == "__main__":
    main()

