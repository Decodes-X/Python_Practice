"""
Single-operator CNC scheduling:
- Multiple machines (M1, M2, ...)
- Single operator who performs a setup immediately before each job
- Objective: minimize makespan (Cmax)

Provides:
- simulate schedule given a global ordering of jobs
- heuristics: FIFO, SPT
- local_search_swap(): pairwise swap local search on the global order
- example usage at the end

"""

from dataclasses import dataclass
from typing import List, Tuple
import random
import csv
import time

@dataclass
class Job:
    job_id: int
    machine_id: str
    setup_time: float   # time operator requires immediately before processing starts
    proc_time: float    # processing time on the machine
    release_time: float = 0.0  # job available from this time

def schedule_from_order(jobs_order: List[Job], n_machines: int) -> Tuple[float, List[Tuple[int,float,float]]]:
    """
    Logic:
      - For each job in the global sequence, schedule it at the earliest time satisfying:
          t >= machine_available[machine]
          t >= operator_available + setup_time  (since operator must be free early enough to perform setup that ends at t)
          t >= release_time
      - After scheduling job at [t, t + p):
          machine_available[machine] = t + p
          operator_available = t   (operator finishes setup at time t and is free afterwards)
    """
    machines = {f"M{i}": 0.0 for i in range(1, n_machines+1)}
    operator_available = 0.0
    schedule = []
    for job in jobs_order:
        m_avail = machines.get(job.machine_id, 0.0)
        t_start = max(m_avail, operator_available + job.setup_time, job.release_time)
        t_finish = t_start + job.proc_time
        machines[job.machine_id] = t_finish
        operator_available = t_start
        schedule.append((job.job_id, t_start, t_finish))
    makespan = max((f for (_,_,f) in schedule), default=0.0)
    return makespan, schedule

def heuristic_order(jobs: List[Job], heuristic: str = "FIFO") -> List[Job]:
    """
    Return an ordering of jobs according to heuristic.
    Supported heuristics: "FIFO" (by job_id), "SPT" (shortest processing time first).
    """
    if heuristic == "FIFO":
        return sorted(jobs, key=lambda x: x.job_id)
    elif heuristic == "SPT":
        return sorted(jobs, key=lambda x: x.proc_time)
    else:
        raise ValueError("Unsupported heuristic")


